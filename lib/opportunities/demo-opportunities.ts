/**
 * Built-in implementation of IOpportunityProvider for demo listings.
 */
export class DemoOpportunityProvider implements IOpportunityProvider {
  readonly name = "PathPilot Starter Demo Provider";

  async getOpportunities(): Promise<Opportunity[]> {
    return STARTER_DEMO_OPPORTUNITIES;
  }

  async getOpportunityById(id: string): Promise<Opportunity | null> {
    return STARTER_DEMO_OPPORTUNITIES.find((o) => o.id === id) || null;
  }
}

export const defaultOpportunityProvider = new DemoOpportunityProvider();
