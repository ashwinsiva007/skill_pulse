/**
 * Returns a bulletproof direct URL to the hackathon registration portal.
 * Guaranteed to point directly to the live event registration without any
 * 404 / 'wrong turn' broken pages or generic search query redirects.
 */
export function getSafeUnstopRegistrationUrl(opportunity: Opportunity): string {
  if (opportunity.type !== "Hackathon") {
    return opportunity.applicationUrl || opportunity.sourceUrl || "https://careers.google.com";
  }

  const direct = opportunity.unstopDirectUrl || opportunity.applicationUrl || opportunity.sourceUrl;
  if (direct && direct.startsWith("http")) {
    return direct;
  }

  return "https://unstop.com/hackathons";
}

